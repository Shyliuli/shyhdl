//! Verilog-2005 generation.
//!
//! The output keeps the structure a reader can follow: one `module` per
//! hardware struct specialisation, one instantiation per `#[instance]` field,
//! `assign` for continuous wiring, `always @(*)` for the default
//! combinational logic and an
//! edge-triggered `always` for `always!`.
//!
//! Names are the source names; the only names the compiler introduces are
//! temporaries derived from a source position (`t_l12_c9`), never a hash
//! Every generated item carries the source line it came from.

use std::fmt::Write as _;

use crate::frontend::mir::{
    BinOp, BodyItem, CaseArm, Design, Expr, ExprKind, LValue, Module, Process, ProcessKind,
    SignalId, SignalKind, SignalScope, Stmt, Ty, UnOp,
};

/// Render the whole design as one Verilog-2005 file.
pub(crate) fn emit(design: &Design) -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "// Generated by the ShyHDL frontend from {}.",
        design.source_name()
    );
    let _ = writeln!(
        out,
        "// Verilog-2005. Do not edit: regenerate from the ShyHDL source."
    );
    let _ = writeln!(out, "// Top module: {}.", design.top().verilog_name);
    for module in design.modules() {
        out.push('\n');
        emit_module(module, &mut out);
    }
    out
}

fn emit_module(module: &Module, out: &mut String) {
    let params = if module.params.is_empty() {
        String::new()
    } else {
        let list: Vec<String> = module
            .params
            .iter()
            .map(|param| format!("{}={}", param.name, param.value))
            .collect();
        format!(" [{}]", list.join(", "))
    };
    let _ = writeln!(
        out,
        "// {}{} (source struct `{}`)",
        module.verilog_name, params, module.source_name
    );

    if module.ports.is_empty() {
        let _ = writeln!(out, "module {} ();", module.verilog_name);
    } else {
        let _ = writeln!(out, "module {} (", module.verilog_name);
        let count = module.ports.len();
        for (index, port) in module.ports.iter().enumerate() {
            let signal = &module.signals[port.signal];
            let declaration = format!(
                "{} {}",
                port.dir.verilog_keyword(),
                format_declaration(signal.kind, &signal.ty, &port.verilog_name)
            );
            let comma = if index + 1 == count { "" } else { "," };
            let _ = writeln!(out, "    {declaration}{comma}  // {}", port.source);
        }
        let _ = writeln!(out, ");");
    }

    // Declarations of everything that is not a port and not a process local.
    // Port membership is decided by `module.ports`, not by `SignalKind`: an
    // output driven by a process is a `reg`, and declaring it twice would be an
    // error in Verilog.
    let port_signals: Vec<SignalId> = module.ports.iter().map(|port| port.signal).collect();
    let mut wires: Vec<String> = Vec::new();
    let mut regs: Vec<String> = Vec::new();
    for (index, signal) in module.signals.iter().enumerate() {
        if !matches!(signal.scope, SignalScope::Module) {
            continue;
        }
        if port_signals.contains(&index) {
            continue;
        }
        let line = format_declaration(signal.kind, &signal.ty, &signal.name);
        match signal.kind {
            SignalKind::Reg => regs.push(line),
            _ => wires.push(line),
        }
    }
    if !wires.is_empty() || !regs.is_empty() {
        out.push('\n');
        for line in wires.iter().chain(regs.iter()) {
            let _ = writeln!(out, "    {line};");
        }
    }

    // A memory is an unpacked array of words, not a wider packed signal: that
    // is the shape `read(addr)` and `write(addr, data)` address, and it stays a
    // plain `reg` array whatever the synthesis tool decides to infer.
    if !module.memories.is_empty() {
        out.push('\n');
        for memory in &module.memories {
            let signing = if memory.element.is_signed() {
                " signed"
            } else {
                ""
            };
            let _ = writeln!(
                out,
                "    reg{signing} [{}:0] {} [0:{}];",
                memory.element.width() - 1,
                memory.name,
                memory.depth - 1
            );
        }
    }

    // Instances first, then the continuous wiring, then the processes: the
    // connection order in the source does not change the emitted topology
    let mut wrote_section = false;
    for instance in &module.instances {
        out.push('\n');
        let _ = writeln!(out, "    // {}", instance.source);
        let _ = writeln!(
            out,
            "    {} {} (",
            instance.module_verilog_name, instance.verilog_name
        );
        let count = instance.connections.len();
        for (position, connection) in instance.connections.iter().enumerate() {
            let comma = if position + 1 == count { "" } else { "," };
            let _ = writeln!(
                out,
                "       .{}({}){comma}",
                connection.port,
                expression(module, &connection.expr)
            );
        }
        let _ = writeln!(out, "    );");
        wrote_section = true;
    }

    let assignments: Vec<(&LValue, &Expr, &crate::metadata::SourceSpan)> = module
        .body
        .iter()
        .filter_map(|item| match item {
            BodyItem::Assign {
                target,
                value,
                source,
            } => Some((target, value, source)),
            _ => None,
        })
        .collect();
    if !assignments.is_empty() {
        out.push('\n');
        for (target, value, source) in assignments {
            let _ = writeln!(out, "    // {source}");
            let _ = writeln!(
                out,
                "    assign {} = {};",
                lvalue(module, target),
                expression(module, value)
            );
        }
        wrote_section = true;
    }

    for process in module.processes() {
        out.push('\n');
        emit_process(module, process, out);
        wrote_section = true;
    }

    if !wrote_section
        && module
            .signals
            .iter()
            .any(|signal| !matches!(signal.kind, SignalKind::Port(_)))
    {
        // Nothing to emit: a module with only ports and no body is still valid.
    }

    let _ = writeln!(out, "endmodule");
}

/// One declaration line: `wire signed [7:0] x`, `reg x`.
///
/// An `int<W>` signal is declared `signed`, so the RTL says how its bits are to
/// be read; a struct value and `uint<W>` stay unsigned, because their bits are
/// what they are.
fn format_declaration(kind: SignalKind, ty: &Ty, name: &str) -> String {
    let keyword = match kind {
        SignalKind::Reg => "reg",
        _ => "wire",
    };
    let signing = if ty.is_signed() { " signed" } else { "" };
    // An array is declared packed even when it is one bit wide: a run-time
    // element select needs a range to address, and Verilog has no bit-select of
    // a scalar.
    let packed = !matches!(ty, Ty::Bool) && (ty.width() > 1 || matches!(ty, Ty::Array { .. }));
    if packed {
        format!("{keyword}{signing} [{}:0] {name}", ty.width() - 1)
    } else {
        format!("{keyword}{signing} {name}")
    }
}

fn emit_process(module: &Module, process: &Process, out: &mut String) {
    let _ = writeln!(out, "    // {}", process.source);
    match &process.kind {
        ProcessKind::Comb => {
            let _ = writeln!(out, "    always @(*) begin : {}", process.label);
        }
        ProcessKind::Seq { clock, resets } => {
            let clock_name = &module.signals[clock.signal].name;
            let mut sensitivity = format!("{} {}", clock.edge.verilog(), clock_name);
            for reset in resets {
                let reset_name = &module.signals[reset.signal].name;
                let _ = write!(sensitivity, " or {} {}", reset.edge.verilog(), reset_name);
            }
            let _ = writeln!(out, "    always @({sensitivity}) begin : {}", process.label);
        }
    }

    if !process.locals.is_empty() {
        for local in &process.locals {
            let signal = &module.signals[*local];
            let _ = writeln!(
                out,
                "        {};",
                format_declaration(SignalKind::Reg, &signal.ty, &signal.name)
            );
        }
    }

    statements(module, &process.body, 2, out);
    let _ = writeln!(out, "    end");
}

fn statements(module: &Module, list: &[Stmt], indent: usize, out: &mut String) {
    let pad = "    ".repeat(indent);
    for statement in list {
        match statement {
            Stmt::Assign {
                target,
                value,
                nonblocking,
                ..
            } => {
                let operator = if *nonblocking { "<=" } else { "=" };
                let _ = writeln!(
                    out,
                    "{pad}{} {operator} {};",
                    lvalue(module, target),
                    expression(module, value)
                );
            }
            Stmt::If {
                cond,
                then_body,
                else_body,
                ..
            } => {
                let _ = writeln!(out, "{pad}if ({}) begin", expression(module, cond));
                statements(module, then_body, indent + 1, out);
                if else_body.is_empty() {
                    let _ = writeln!(out, "{pad}end");
                } else {
                    let _ = writeln!(out, "{pad}end else begin");
                    statements(module, else_body, indent + 1, out);
                    let _ = writeln!(out, "{pad}end");
                }
            }
            Stmt::MemWrite {
                memory,
                addr,
                value,
                ..
            } => {
                let memory = &module.memories[*memory];
                let _ = writeln!(
                    out,
                    "{pad}{}[{}] <= {};",
                    memory.name,
                    // The address is unsigned by type, whatever the signal it
                    // was read from is declared as.
                    typed_operand(module, addr),
                    expression(module, value)
                );
            }
            Stmt::Case {
                kind,
                scrutinee,
                arms,
                default,
                ..
            } => {
                let _ = writeln!(
                    out,
                    "{pad}{} ({})",
                    kind.verilog(),
                    expression(module, scrutinee)
                );
                for arm in arms {
                    emit_case_arm(module, arm, indent + 1, out);
                }
                if let Some(default) = default {
                    let _ = writeln!(out, "{pad}    default: begin");
                    statements(module, default, indent + 2, out);
                    let _ = writeln!(out, "{pad}    end");
                }
                let _ = writeln!(out, "{pad}endcase");
            }
        }
    }
}

fn emit_case_arm(module: &Module, arm: &CaseArm, indent: usize, out: &mut String) {
    let pad = "    ".repeat(indent);
    let values: Vec<String> = arm
        .values
        .iter()
        .map(|value| expression(module, value))
        .collect();
    let _ = writeln!(out, "{pad}{}: begin", values.join(", "));
    statements(module, &arm.body, indent + 1, out);
    let _ = writeln!(out, "{pad}end");
}

fn lvalue(module: &Module, target: &LValue) -> String {
    match target {
        LValue::Signal { signal, range, .. } => match range {
            Some((lo, hi)) => slice(module, *signal, *lo, *hi),
            None => module.signals[*signal].name.clone(),
        },
    }
}

fn expression(module: &Module, expr: &Expr) -> String {
    match &expr.kind {
        ExprKind::Const { value, width } => constant(&expr.ty, *value, *width),
        ExprKind::Pattern { value, care, width } => pattern_constant(*value, *care, *width),
        ExprKind::Signal(signal) => module.signals[*signal].name.clone(),
        ExprKind::Slice { signal, lo, hi } => slice(module, *signal, *lo, *hi),
        ExprKind::Binary { op, lhs, rhs } => binary(module, *op, lhs, rhs),
        ExprKind::Unary { op, operand } => match op {
            UnOp::Not => format!("(!{})", expression(module, operand)),
            UnOp::BitNot => format!("(~{})", expression(module, operand)),
            UnOp::Neg => format!("(-{})", expression(module, operand)),
        },
        ExprKind::Ternary {
            cond,
            then_expr,
            else_expr,
        } => format!(
            "({} ? {} : {})",
            expression(module, cond),
            expression(module, then_expr),
            expression(module, else_expr)
        ),
        ExprKind::Concat(elements) => {
            if elements.len() == 1 {
                return expression(module, &elements[0]);
            }
            let parts: Vec<String> = elements
                .iter()
                .map(|element| expression(module, element))
                .collect();
            format!("{{{}}}", parts.join(", "))
        }
        ExprKind::Replicate { count, value } => {
            format!("{{{}{{{}}}}}", count, expression(module, value))
        }
        ExprKind::BitSelect { signal, index } => bit_select(module, *signal, index),
        ExprKind::MemRead { memory, addr } => {
            let memory = &module.memories[*memory];
            // An index past the last element reads `x` in Verilog, which is the
            // unknown this language wants; nothing is added to guard it. The
            // address is marked unsigned by its type, so a signed signal cannot
            // turn it into a negative index.
            format!("{}[{}]", memory.name, typed_operand(module, addr))
        }
    }
}

/// A run-time bit or element select.
///
/// The signal's own type decides what the index means: a `[T; N]` signal selects
/// element `index`, anything else selects bit `index` - today's behaviour,
/// unchanged.
///
/// An element select is guarded, so only an index inside the array can name
/// memory at all: anything else is the standard unknown, which is what reading
/// past a vector means. The offset is computed only on the guarded branch, and
/// `len` and the element width are plain decimals: Verilog evaluates an unsized
/// decimal in at least 32 bits, and a valid offset never exceeds the maximum
/// supported width (65536), so no offset the guard lets through can be
/// truncated - and no other offset is observable.
fn bit_select(module: &Module, signal: SignalId, index: &Expr) -> String {
    let info = &module.signals[signal];
    // The index is an unsigned value, and it is written as one: a cast can leave
    // it on a net that is declared `signed`, and a signed index would compare and
    // multiply as a negative number.
    let index = typed_operand(module, index);
    if let Ty::Array { element, len } = &info.ty {
        let width = element.width();
        let unknown = format!("{{{width}{{1'bx}}}}");
        return format!(
            "(({index} < {len}) ? {}[({index} * {width}) +: {width}] : {unknown})",
            info.name,
        );
    }
    // A one-bit signal is declared as a scalar, and Verilog has no bit-select of
    // a scalar: index 0 reads the signal, and any other index is unknown.
    if info.width() == 1 {
        return format!("(({index} == 0) ? {} : 1'bx)", info.name);
    }
    format!("{}[{index}]", info.name)
}

/// Bits `[lo, hi)` of a signal, as Verilog text.
fn slice(module: &Module, signal: SignalId, lo: u32, hi: u32) -> String {
    let info = &module.signals[signal];
    if info.width() == 1 {
        // A one-bit signal is a scalar: selecting it would be a bit-select on a
        // scalar, so the name is used directly.
        return info.name.clone();
    }
    if lo == 0 && hi == info.width() {
        return info.name.clone();
    }
    if hi - lo == 1 {
        format!("{}[{lo}]", info.name)
    } else {
        format!("{}[{}:{lo}]", info.name, hi - 1)
    }
}

/// A binary operation.
///
/// Only two operators read their operands' signedness: the ordering comparisons
/// and the arithmetic shift. Everywhere else the result's bits do not depend on
/// it, so the operands are emitted as written and no cast noise is added.
fn binary(module: &Module, op: BinOp, lhs: &Expr, rhs: &Expr) -> String {
    // `>>>` fills with the sign bit; `>>` would fill with zeros and turn a
    // negative value into a large positive one.
    if op == BinOp::Shr && lhs.ty.is_signed() {
        return format!(
            "({} >>> {})",
            signed_operand(module, lhs),
            expression(module, rhs)
        );
    }
    if matches!(op, BinOp::Lt | BinOp::Le | BinOp::Gt | BinOp::Ge) {
        return format!(
            "({} {} {})",
            typed_operand(module, lhs),
            op.verilog(),
            typed_operand(module, rhs)
        );
    }
    format!(
        "({} {} {})",
        expression(module, lhs),
        op.verilog(),
        expression(module, rhs)
    )
}

/// An operand of an operation whose *bits* depend on the reading, requested from
/// the type of the value rather than from how it happens to be declared.
///
/// A part-select is unsigned in Verilog even when the value it came from is
/// signed, a whole-value slice may be emitted as the (signed) signal itself, and
/// a cast changes the type without changing the signal - so an ordering
/// comparison names the reading it means. A constant is written with the reading
/// its type asks for already (`4'sd0`, `-4'sd1`).
fn typed_operand(module: &Module, expr: &Expr) -> String {
    if matches!(expr.kind, ExprKind::Const { .. }) {
        return expression(module, expr);
    }
    if expr.ty.is_signed() {
        format!("$signed({})", expression(module, expr))
    } else {
        format!("$unsigned({})", expression(module, expr))
    }
}

/// A signed operand of the arithmetic shift, which has no count to protect.
fn signed_operand(module: &Module, expr: &Expr) -> String {
    if expr.ty.is_signed() && !matches!(expr.kind, ExprKind::Const { .. }) {
        return format!("$signed({})", expression(module, expr));
    }
    expression(module, expr)
}

/// A constant, written the way Verilog spells it.
///
/// A negative value is a negated magnitude, `-8'sd1`: `8'sd-1` is not a literal
/// at all. A value of a signed type is written signed - at every width, a
/// one-bit `int<1>` included - so that it reads as signed next to another
/// signed operand; `bool` and `uint<W>` are written unsigned.
fn constant(ty: &Ty, value: i128, width: u32) -> String {
    match width {
        0 => format!("{value}"),
        _ if value < 0 => format!("-{width}'sd{}", value.unsigned_abs()),
        _ if ty.is_signed() => format!("{width}'sd{value}"),
        1 => format!("1'b{}", value & 1),
        _ => format!("{width}'d{value}"),
    }
}

/// A constant with don't-care bits, as a `casez` arm value spells it: `?` where
/// `care` is clear, the bit itself everywhere else.
///
/// All bits cared about would be an ordinary constant, and one bit is `1'b1`
/// rather than `1'b1` with a sizing quirk, so those two cases keep the plain
/// spelling.
fn pattern_constant(value: u128, care: u128, width: u32) -> String {
    if width == 0 {
        return "0".to_string();
    }
    let covered = if width >= 128 {
        u128::MAX
    } else {
        (1u128 << width) - 1
    };
    if care & covered == covered {
        return constant(&Ty::UInt(width), value as i128, width);
    }
    let bits: String = (0..width)
        .rev()
        .map(|bit| {
            if care & (1u128 << bit) == 0 {
                '?'
            } else if value & (1u128 << bit) != 0 {
                '1'
            } else {
                '0'
            }
        })
        .collect();
    format!("{width}'b{bits}")
}
